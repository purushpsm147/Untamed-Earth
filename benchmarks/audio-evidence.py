#!/usr/bin/env python3
"""AUD-01 review package: turn rendered recordings into listening copies, spectrograms and cue sheets.

Input:  test-artifacts/audio/<scenario>.wav + .cues.json (npm run audio:render), calibration.wav/.json
Output: docs/evidence/audio/<scenario>.mp3, <scenario>.png (spectrogram), <scenario>.md (cue sheet),
        calibration.mp3, index.json (sha256 of source WAVs, loudness, counts).
Needs ffmpeg on PATH. Standard library only.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

SRC = 'test-artifacts/audio'
OUT = 'docs/evidence/audio'
SEASONS = ['Winter', 'Summer', 'Monsoon', 'Post-monsoon']


def sh(args):
    return subprocess.run(args, check=True, capture_output=True, text=True)


def loudness(wav):
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', wav, '-af', 'ebur128=peak=true', '-f', 'null', '-'], capture_output=True, text=True)
    i = re.findall(r'I:\s+(-?[\d.]+) LUFS', r.stderr)
    p = re.findall(r'Peak:\s+(-?[\d.]+) dBFS', r.stderr)
    return (float(i[-1]) if i else None, float(p[-1]) if p else None)


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


BANDS = [63, 125, 250, 500, 1000, 2000, 4000, 8000, 16000]


def octave_levels(wav):
    """Octave-band levels (dB re full scale, both channels summed) over the whole file. Needs numpy; None without it.

    The spectrogram image uses a LINEAR frequency axis: an earlier log-frequency rendering showed a bright band near
    1-2 kHz that was a display artefact (low rows repeat the same FFT bins), not a spectral peak. These numbers are the
    measurement to rely on."""
    try:
        import numpy as np  # noqa: PLC0415
        import wave  # noqa: PLC0415
    except ImportError:
        return None
    w = wave.open(wav)
    x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).reshape(-1, 2).astype(float) / 32768
    out = {}
    for ch in range(2):
        X = np.abs(np.fft.rfft(x[:, ch] * np.hanning(len(x)))) ** 2
        f = np.fft.rfftfreq(len(x), 1 / w.getframerate())
        for fc in BANDS:
            m = (f >= fc / 2 ** 0.5) & (f < fc * 2 ** 0.5)
            out[fc] = out.get(fc, 0) + float(X[m].sum())
    ref = 10 * np.log10(sum(out.values()) + 1e-30)
    return {fc: round(10 * np.log10(v + 1e-30) - ref, 1) for fc, v in out.items()}


def hhmm(h):
    return f'{int(h):02d}:{int((h % 1) * 60):02d}'


def cue_sheet(name, d, lufs, peak, wav_sha, bands):
    m = d['meta']
    c = m['conditions']
    L = m['listener']
    lines = [
        f'# Listening cue sheet: `{name}`',
        '',
        *([f'> **{d["variant"]}.** Compare with `{name.split(".")[0]}` (production default: state-derived calls off).', ''] if d.get('variant') else []),
        'Generated by `benchmarks/audio-evidence.py` from the offline render (`npm run audio:render`). Every row is a sound the soundscape started, with its cause. **Nothing here has been listening-verified.**',
        '',
        f'- Scenario: {m.get("title", name)}. World: seed {m.get("seed", "?")}, day {int(c["timeH"] // 24)}, {hhmm(c["hour"])}, {SEASONS[c["season"]]}, weather {c["weather"]}, {c["temperatureC"]} °C (simulation tick {m["simTickStart"]} -> {m["simTickEnd"]})',
        f'- Listener: x {L["x"]:.1f}, z {L["z"]:.1f}, y {L["y"]:.1f} m (terrain + 1.7 m ear height), yaw {L["yaw"]:.2f} rad. {m["note"]}',
        f'- Render: {d["browser"].split(" ")[-2]} offline, 48 kHz stereo, HRTF for calls; render speed {m["renderSpeed"]}x real time; source WAV sha256 `{wav_sha[:16]}…`',
        f'- Level: {lufs} LUFS integrated, true peak {peak} dBFS (game default volume 0.7, not normalised).',
        f'- Voices: event calls {m["counters"]["eventCalls"]}, state-derived calls {m["counters"]["stateCalls"]}, movement {m["counters"]["movement"]}, thunder {m["counters"]["thunder"]}; rejected by the budget {m["counters"]["rejected"]}; peak concurrent {m["poolPeak"]}.',
        f'- Routing of real events: ' + ', '.join(f'{k} {v}' for k, v in m['route'].items() if v),
        '',
        '## Measured octave-band balance (dB relative to the total; whole recording)',
        '',
        ('| ' + ' | '.join(f'{b} Hz' for b in BANDS) + ' |\n|' + '---:|' * len(BANDS) + '\n| ' + ' | '.join(str(bands[b]) for b in BANDS) + ' |') if bands else '_numpy not available: band levels not computed._',
        '',
        f'Spectrogram (linear frequency axis, 0-12 kHz): `{name}.jpg`.',
        '',
    ]
    if m.get('expected'):
        lines += ['## Real simulation events in range (look-ahead, same engine)', '', '| t (s) | event | species | distance (m) |', '|---:|---|---|---:|']
        lines += [f'| {e["t"]} | {e["kind"]} | {e["species"]} | {e["d"]} |' for e in m['expected']]
        lines.append('')
    lines += ['## Sounds and decisions', '', 'Azimuth: 0 ahead, +90 right, -90 left, ±180 behind. Movement sounds are listed only within 12 m.', '',
              'Provenance: `sim-event` = a real simulation event; `animal-state` = derived from a real animal\'s state (for calls: NOT a simulated vocal event); `environment` = weather/time/habitat.', '',
              '| t (s) | kind | sound | distance (m) | azimuth | terrain occl. | foliage (m) | level (dB) | provenance | cause |', '|---:|---|---|---:|---:|---:|---:|---:|---|---|']
    for q in d['cues']:
        pv = q.get('provenance') or {}
        src = pv.get('source', '?') + (f" ({pv['event']} #{pv['animalId']})" if pv.get('source') == 'sim-event' else '')
        lines.append('| {t:.2f} | {kind} | {label} | {d} | {az} | {to} | {fo} | {g} | {src} | {why} |'.format(
            t=q['t'], kind=q['kind'], label=q['label'], d=q.get('distanceM', ''), az=q.get('azimuthDeg', ''), to=q.get('terrainOcclusion', ''),
            fo=q.get('foliageM', ''), g=q.get('gainDb', ''), src=src, why=q['why'].replace('|', '/')))
    return '\n'.join(lines) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    index = {}
    names = sorted(f[:-10] for f in os.listdir(SRC) if f.endswith('.cues.json'))
    if not names:
        sys.exit('no recordings: run npm run audio:render first')
    for n in names:
        wav = f'{SRC}/{n}.wav'
        d = json.load(open(f'{SRC}/{n}.cues.json'))
        lufs, peak = loudness(wav)
        digest = sha256(wav)
        sh(['ffmpeg', '-y', '-hide_banner', '-loglevel', 'error', '-i', wav, '-codec:a', 'libmp3lame', '-b:a', '128k', f'{OUT}/{n}.mp3'])
        sh(['ffmpeg', '-y', '-hide_banner', '-loglevel', 'error', '-i', wav, '-lavfi',
            'showspectrumpic=s=1100x360:legend=1:color=intensity:scale=log:stop=12000', '-q:v', '5', f'{OUT}/{n}.jpg'])
        bands = octave_levels(wav)
        open(f'{OUT}/{n}.md', 'w').write(cue_sheet(n, d, lufs, peak, digest, bands))
        m = d['meta']
        index[n] = {'wavSha256': digest, 'lufs': lufs, 'truePeakDbfs': peak, 'octaveBandsDbRel': bands,
                    'counters': m['counters'], 'poolPeak': m['poolPeak'], 'renderSpeed': m['renderSpeed'], 'conditions': m['conditions'], 'note': m['note']}
    cal = f'{SRC}/calibration.wav'
    if os.path.exists(cal):
        sh(['ffmpeg', '-y', '-hide_banner', '-loglevel', 'error', '-i', cal, '-codec:a', 'libmp3lame', '-b:a', '128k', f'{OUT}/calibration.mp3'])
        index['calibration'] = {'wavSha256': sha256(cal), **json.load(open(f'{SRC}/calibration.json'))}
    json.dump(index, open(f'{OUT}/index.json', 'w'), indent=1)
    print('\n'.join(f'{k}: {v.get("lufs")} LUFS' for k, v in index.items()))


if __name__ == '__main__':
    main()
